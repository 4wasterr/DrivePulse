const { test } = require('node:test');
const assert = require('node:assert/strict');
const { PGlite } = require('@electric-sql/pglite');
const { postgresSchema } = require('../schema');

test('the earlier JSONB and timestamp scaffold migrates twice without losing data', async t => {
  const engine = new PGlite();
  t.after(() => engine.close());
  const legacy = postgresSchema.split('-- Upgrade')[0]
    .replaceAll('rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,', '')
    .replaceAll('payload TEXT NOT NULL', "payload JSONB NOT NULL DEFAULT '{}'::jsonb")
    .replace("saved TEXT NOT NULL DEFAULT '[]'", "saved JSONB NOT NULL DEFAULT '[]'::jsonb")
    .replace("created_at TEXT NOT NULL DEFAULT ''", 'created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()')
    .replace("last_login_at TEXT NOT NULL DEFAULT ''", 'last_login_at TIMESTAMPTZ')
    .replace('archived_at TEXT', 'archived_at TIMESTAMPTZ')
    .replace('uploaded_at TEXT NOT NULL', 'uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()')
    .replace('created_at TEXT NOT NULL', 'created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()')
    .replace('at TEXT NOT NULL,', 'at TIMESTAMPTZ NOT NULL DEFAULT NOW(),');
  await engine.exec(legacy);
  await engine.exec(`
    INSERT INTO users(id,email,name,role,salt,password_hash,created_at)
      VALUES('legacy-user','legacy@example.com','Existing renter','client','salt','stored-hash','2026-10-22T08:00:00Z');
    INSERT INTO bookings(id,owner_id,payload) VALUES('legacy-booking','legacy-user','{"id":"legacy-booking","version":3}');
  `);
  for (let i = 0; i < 2; i++) await engine.exec('BEGIN;\n' + postgresSchema + '\nCOMMIT;');
  const user = (await engine.query('SELECT * FROM users WHERE id=$1', ['legacy-user'])).rows[0];
  assert.equal(user.created_at, '2026-10-22T08:00:00.000Z');
  assert.equal(user.last_login_at, '');
  assert.equal(user.saved, '[]');
  const booking = (await engine.query('SELECT payload FROM bookings WHERE id=$1', ['legacy-booking'])).rows[0];
  assert.deepEqual(JSON.parse(booking.payload), { id: 'legacy-booking', version: 3 });
  assert.ok(user.rowid);
});
