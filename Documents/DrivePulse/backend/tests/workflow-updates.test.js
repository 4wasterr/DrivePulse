const { test } = require('node:test');
const assert = require('node:assert/strict');
const { createApp } = require('../application');
const { cleanDemoData } = require('../demo-cleanup');
const { testDatabase } = require('./helpers/database');
const { mkdtempSync, readdirSync, unlinkSync, rmdirSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const D = require('../domain');

for (const engine of ['sqlite', 'postgres']) test(`${engine}: idle expiry, dynamic locations, deposit ledger and backed-up demo purge`, async t => {
  const previous = process.env.DRIVEPULSE_TEST_POSTGRES;
  process.env.DRIVEPULSE_TEST_POSTGRES = engine === 'postgres' ? 'true' : '';
  const database = await testDatabase();
  if (previous === undefined) delete process.env.DRIVEPULSE_TEST_POSTGRES; else process.env.DRIVEPULSE_TEST_POSTGRES = previous;
  const { app, db } = await createApp({ dbPath: ':memory:', database, seedDemo: true, mailer: null });
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await db.close(); });
  async function request(path, cookie, body) {
    const response = await fetch(base + path, { method: body ? 'POST' : 'GET', headers: { ...(cookie ? { Cookie: cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, data: await response.json(), headers: response.headers, cookie: response.headers.get('set-cookie')?.split(';')[0] };
  }
  const login = await request('/auth/login', null, { username: 'bkagent', password: 'bkagent' });
  assert.equal(login.status, 200);
  const cookie = login.cookie, id = login.data.user.id;
  assert.equal((await request('/workspace', cookie)).data.bookings.length, 0, 'demo logins must not seed operational data');
  const idle = Date.now() - 14 * 60000;
  await db.prepare('UPDATE sessions SET last_activity=? WHERE user_id=?').run(idle, id);
  await request('/session', cookie); await request('/workspace', cookie);
  assert.equal((await db.prepare('SELECT last_activity FROM sessions WHERE user_id=?').get(id)).last_activity, idle, 'polling must not renew inactivity');
  assert.equal((await request('/session/activity', cookie, {})).status, 200);
  assert.ok((await db.prepare('SELECT last_activity FROM sessions WHERE user_id=?').get(id)).last_activity > idle);
  const branches = (await request('/locations')).data;
  assert.equal(branches.length, 4);
  await db.prepare('INSERT INTO fleet_records(kind,id,payload) VALUES(?,?,?)').run('location', 'new-depot', JSON.stringify({ id: 'new-depot', name: 'New operational depot', active: true }));
  assert.ok((await request('/locations')).data.some(location => location.name === 'New operational depot'));
  const date = offset => new Date(Date.now() + offset * D.DAY).toISOString().slice(0, 10);
  const body = { vehicleId: 'toyota-vios', start: date(2), end: date(5), startTime: '10:00', endTime: '10:00', pickup: 'New operational depot', dropoff: branches[0].name, renter: { name: 'Test renter', phone: '09171234567' }, transactionReference: 'MANUAL-REFERENCE' };
  assert.equal((await request('/agent/bookings', cookie, body)).status, 400);
  const created = await request('/agent/bookings', cookie, { ...body, customerConfirmed: true });
  assert.equal(created.status, 201, JSON.stringify(created.data));
  assert.match(created.data.transactionReference, /^DP-TXN-[A-F0-9]{16}$/);
  const retained = await request('/agent/bookings', cookie, { ...body, customerConfirmed: true, vehicleId: 'honda-city' });
  assert.equal(retained.status, 201);
  assert.notEqual(retained.data.transactionReference, created.data.transactionReference);
  created.data.payments = [{ id: 'expected-deposit', type: 'deposit', amount: 5000, status: 'pending', method: 'Cash', reference: 'Awaiting cash at the counter' }];
  await db.prepare('UPDATE bookings SET payload=? WHERE id=?').run(JSON.stringify(created.data), created.data.id);
  const paid = await request(`/agent/bookings/${created.data.id}/payment`, cookie, { version: created.data.version, type: 'deposit', amount: 5000, received: true });
  assert.equal(paid.status, 200, JSON.stringify(paid.data));
  assert.equal(paid.data.billing.depositPaid, 5000); assert.equal(paid.data.billing.depositBalance, 0);
  assert.equal(paid.data.payments.length, 1); assert.equal(paid.data.payments[0].id, 'expected-deposit');
  assert.ok(paid.data.payments[0].receipt); assert.match(paid.data.payments[0].reference, /^CASH-/);
  const excess = await request(`/agent/bookings/${paid.data.id}/payment`, cookie, { version: paid.data.version, type: 'deposit', amount: 1, received: true });
  assert.equal(excess.status, 400);
  retained.data.payments = [{ id: 'partial-deposit', type: 'deposit', amount: 5000, status: 'pending', method: 'Cash', reference: 'Awaiting cash at the counter' }];
  await db.prepare('UPDATE bookings SET payload=? WHERE id=?').run(JSON.stringify(retained.data), retained.data.id);
  const partial = await request(`/agent/bookings/${retained.data.id}/payment`, cookie, { version: retained.data.version, type: 'deposit', amount: 2000, received: true });
  assert.equal(partial.status, 200); assert.equal(partial.data.billing.depositBalance, 3000);
  const remaining = await request(`/agent/bookings/${retained.data.id}/payment`, cookie, { version: partial.data.version, type: 'deposit', amount: 3000, received: true });
  assert.equal(remaining.status, 200); assert.equal(remaining.data.billing.depositBalance, 0);
  assert.ok(remaining.data.payments.every(payment => payment.status === 'confirmed'));
  const vehicles = (await request('/vehicles')).data;
  assert.equal(vehicles.length, 16); assert.equal(vehicles.find(vehicle => vehicle.id === 'nissan-urvan').seats, 15);
  assert.equal(new Set(vehicles.map(vehicle => vehicle.plate.replace(/\s/g, ''))).size, 16);
  assert.ok(vehicles.every(vehicle => /^[A-Z]{3} \d{4}$/.test(vehicle.plate)));
  const existingProfile = await db.prepare("SELECT payload FROM fleet_records WHERE kind='vehicle' AND id='bmw-3'").get();
  const profile = { ...JSON.parse(existingProfile.payload), plate: 'ABC 9876' };
  await db.prepare("UPDATE fleet_records SET payload=? WHERE kind='vehicle' AND id='bmw-3'").run(JSON.stringify(profile));
  await createApp({ database: db, seedDemo: false, mailer: null });
  assert.equal((await request('/vehicles')).data.find(vehicle => vehicle.id === 'bmw-3').plate, 'ABC 9876');
  assert.equal(vehicles.find(vehicle => vehicle.id === 'hyundai-staria').fuelType, 'Diesel');
  const demo = { ...paid.data, sample: true };
  if (engine === 'postgres') {
    await db.exec('CREATE TRIGGER trg_audit_no_delete BEFORE DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION drivepulse_immutable()');
    await db.exec('CREATE TRIGGER trg_rental_doc_no_delete BEFORE DELETE ON rental_documents FOR EACH ROW EXECUTE FUNCTION drivepulse_immutable()');
  }
  await db.prepare('UPDATE bookings SET payload=? WHERE id=?').run(JSON.stringify(demo), demo.id);
  await db.prepare('INSERT INTO fleet_records(kind,id,payload) VALUES(?,?,?)').run('maintenance', 'mock-repair', JSON.stringify({ id: 'mock-repair', mock: true }));
  const backupDir = mkdtempSync(join(tmpdir(), 'drivepulse-cleanup-'));
  t.after(() => { for (const file of readdirSync(backupDir)) unlinkSync(join(backupDir, file)); rmdirSync(backupDir); });
  assert.equal((await cleanDemoData(db)).applied, false);
  const result = await cleanDemoData(db, { apply: true, backupDir });
  assert.equal(result.bookings, 1); assert.equal(result.operationalRecords, 1); assert.equal(result.preservedBookings, 1); assert.equal(result.preservedAccounts, 4);
  assert.equal((await request('/workspace', cookie)).data.bookings[0].id, retained.data.id);
  assert.equal((await cleanDemoData(db)).bookings, 0, 'a second purge must preserve the unmarked booking');
  await assert.rejects(async () => db.prepare('DELETE FROM audit_log').run(), /immutable/);
  await assert.rejects(async () => db.prepare('DELETE FROM rental_documents').run(), /immutable/);
  await db.prepare('UPDATE sessions SET last_activity=? WHERE user_id=?').run(Date.now() - 15 * 60000, id);
  const expired = await request('/workspace', cookie);
  assert.equal(expired.status, 401); assert.equal(expired.data.code, 'SESSION_EXPIRED');
  assert.match(expired.headers.get('set-cookie'), /drivepulse_session=;/);
  assert.equal(await db.prepare('SELECT token FROM sessions WHERE user_id=?').get(id), undefined);
  assert.equal((await request('/session/activity', cookie, {})).status, 401);
});
