// Keep payloads and timestamps as text so both adapters return the same shape.
const tables = `
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('client','agent','mechanic','manager')),
  salt TEXT NOT NULL, password_hash TEXT NOT NULL, saved TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL DEFAULT '', last_login_at TEXT NOT NULL DEFAULT '',
  email_verified_at TEXT NOT NULL DEFAULT '',
  archived_at TEXT, archived_by TEXT, archive_reason TEXT
);
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS auth_tokens (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('verify_email','reset_password')),
  expires BIGINT NOT NULL,
  issued_at TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS bookings (id TEXT PRIMARY KEY, owner_id TEXT, payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS documents (id TEXT PRIMARY KEY, owner_id TEXT NOT NULL, kind TEXT NOT NULL, name TEXT NOT NULL, mime TEXT NOT NULL, fingerprint TEXT NOT NULL, uploaded_at TEXT NOT NULL, data BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS tickets (id TEXT PRIMARY KEY, owner_id TEXT, payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS fleet_records (kind TEXT NOT NULL, id TEXT NOT NULL, payload TEXT NOT NULL, PRIMARY KEY(kind,id));
CREATE TABLE IF NOT EXISTS rental_documents (id TEXT PRIMARY KEY, booking_id TEXT NOT NULL, kind TEXT NOT NULL, created_at TEXT NOT NULL, payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS vehicles (id TEXT PRIMARY KEY, model TEXT NOT NULL, brand TEXT NOT NULL, category TEXT NOT NULL, rate REAL NOT NULL, plate TEXT NOT NULL, transmission TEXT NOT NULL, seats INTEGER NOT NULL, fuel_type TEXT NOT NULL, tank_capacity INTEGER NOT NULL, mileage INTEGER NOT NULL, status TEXT NOT NULL, payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS audit_log (
  sequence INTEGER PRIMARY KEY AUTOINCREMENT, id TEXT UNIQUE NOT NULL, at TEXT NOT NULL,
  actor_id TEXT, actor TEXT NOT NULL, role TEXT NOT NULL, action TEXT NOT NULL,
  resource TEXT NOT NULL, detail TEXT NOT NULL, status INTEGER NOT NULL,
  old_value TEXT NOT NULL DEFAULT '', new_value TEXT NOT NULL DEFAULT '',
  ip TEXT NOT NULL DEFAULT '', alert_type TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS auth_attempts (address TEXT PRIMARY KEY, started_at BIGINT NOT NULL, attempts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS schema_version (version INTEGER PRIMARY KEY);
CREATE INDEX IF NOT EXISTS idx_documents_owner_kind ON documents(owner_id,kind,uploaded_at);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_user_kind ON auth_tokens(user_id,kind);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_expires ON auth_tokens(expires);
CREATE INDEX IF NOT EXISTS idx_audit_at ON audit_log(at);
`;

const sqliteSchema = tables + ['audit_log', 'rental_documents'].flatMap(table => ['UPDATE', 'DELETE'].map(action =>
  `CREATE TRIGGER IF NOT EXISTS immutable_${table}_${action.toLowerCase()} BEFORE ${action} ON ${table} BEGIN SELECT RAISE(ABORT, 'Records are immutable'); END;`
)).join('\n') + '\nINSERT OR IGNORE INTO schema_version VALUES(1);';

const postgresSchema = tables
  .replace(/BLOB/g, 'BYTEA')
  .replace('sequence INTEGER PRIMARY KEY AUTOINCREMENT', 'sequence BIGSERIAL PRIMARY KEY')
  .replace(/CREATE TABLE IF NOT EXISTS (users|documents|fleet_records) \(/g,
    'CREATE TABLE IF NOT EXISTS $1 (rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,') + `
-- Upgrade the earlier Supabase scaffold without deleting existing records.
ALTER TABLE users ADD COLUMN IF NOT EXISTS rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TEXT;
ALTER TABLE documents ADD COLUMN IF NOT EXISTS rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE fleet_records ADD COLUMN IF NOT EXISTS rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE users ALTER COLUMN saved DROP DEFAULT;
ALTER TABLE users ALTER COLUMN saved TYPE TEXT USING saved::text;
ALTER TABLE users ALTER COLUMN saved SET DEFAULT '[]';
DO $$ DECLARE tab TEXT; col TEXT; BEGIN
  FOREACH tab IN ARRAY ARRAY['bookings','tickets','fleet_records','rental_documents','vehicles'] LOOP
    EXECUTE format('ALTER TABLE %I ALTER COLUMN payload DROP DEFAULT', tab);
    EXECUTE format('ALTER TABLE %I ALTER COLUMN payload TYPE TEXT USING payload::text', tab);
  END LOOP;
  FOREACH col IN ARRAY ARRAY['created_at','last_login_at','archived_at'] LOOP
    EXECUTE format('ALTER TABLE users ALTER COLUMN %I DROP DEFAULT', col);
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='users' AND column_name=col AND data_type='timestamp with time zone') THEN
      EXECUTE format('ALTER TABLE users ALTER COLUMN %I TYPE TEXT USING to_char(%I AT TIME ZONE ''UTC'', ''YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'')', col, col);
    END IF;
  END LOOP;
  FOREACH tab IN ARRAY ARRAY['documents','rental_documents','audit_log'] LOOP
    col := CASE tab WHEN 'documents' THEN 'uploaded_at' WHEN 'rental_documents' THEN 'created_at' ELSE 'at' END;
    EXECUTE format('ALTER TABLE %I ALTER COLUMN %I DROP DEFAULT', tab, col);
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=tab AND column_name=col AND data_type='timestamp with time zone') THEN
      EXECUTE format('ALTER TABLE %I ALTER COLUMN %I TYPE TEXT USING to_char(%I AT TIME ZONE ''UTC'', ''YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'')', tab, col, col);
    END IF;
  END LOOP;
END $$;
UPDATE users SET last_login_at='' WHERE last_login_at IS NULL;
UPDATE users SET email_verified_at=CASE WHEN created_at<>'' THEN created_at ELSE 'verified' END WHERE email_verified_at IS NULL;
ALTER TABLE users ALTER COLUMN created_at SET DEFAULT '';
ALTER TABLE users ALTER COLUMN last_login_at SET DEFAULT '';
ALTER TABLE users ALTER COLUMN last_login_at SET NOT NULL;
ALTER TABLE users ALTER COLUMN email_verified_at SET DEFAULT '';
ALTER TABLE users ALTER COLUMN email_verified_at SET NOT NULL;
CREATE OR REPLACE FUNCTION drivepulse_immutable() RETURNS TRIGGER AS $$
BEGIN RAISE EXCEPTION 'Records are immutable'; END;
$$ LANGUAGE plpgsql;
` + ['audit_log', 'rental_documents'].map(table => `
DROP TRIGGER IF EXISTS drivepulse_immutable ON ${table};
CREATE TRIGGER drivepulse_immutable BEFORE UPDATE OR DELETE ON ${table} FOR EACH ROW EXECUTE FUNCTION drivepulse_immutable();
ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ${table} FROM PUBLIC;
`).join('\n') + `
DO $$ DECLARE tab TEXT; BEGIN
  FOREACH tab IN ARRAY ARRAY['users','sessions','auth_tokens','bookings','documents','tickets','fleet_records','vehicles','auth_attempts','schema_version'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tab);
    EXECUTE format('REVOKE ALL ON %I FROM PUBLIC', tab);
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
    REVOKE ALL ON users,sessions,auth_tokens,bookings,documents,tickets,fleet_records,vehicles,audit_log,rental_documents,auth_attempts,schema_version FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
    REVOKE ALL ON users,sessions,auth_tokens,bookings,documents,tickets,fleet_records,vehicles,audit_log,rental_documents,auth_attempts,schema_version FROM authenticated;
  END IF;
END $$;
INSERT INTO schema_version VALUES(1) ON CONFLICT DO NOTHING;
`;

// Applied automatically by the PostgreSQL adapter when an older database starts.
const emailUpgrade = `
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TEXT;
UPDATE users SET email_verified_at=CASE WHEN created_at<>'' THEN created_at ELSE 'verified' END WHERE email_verified_at IS NULL;
ALTER TABLE users ALTER COLUMN email_verified_at SET DEFAULT '';
ALTER TABLE users ALTER COLUMN email_verified_at SET NOT NULL;
CREATE TABLE IF NOT EXISTS auth_tokens (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('verify_email','reset_password')),
  expires BIGINT NOT NULL,
  issued_at TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_user_kind ON auth_tokens(user_id,kind);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_expires ON auth_tokens(expires);
ALTER TABLE auth_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON auth_tokens FROM PUBLIC;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN REVOKE ALL ON auth_tokens FROM anon; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN REVOKE ALL ON auth_tokens FROM authenticated; END IF;
END $$;
`;

